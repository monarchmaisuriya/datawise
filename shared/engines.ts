// One row per engine. The client reads this table and never branches on an engine's name, so adding
// an engine means one row here and one adapter in server/adapters.
export const ENGINE_IDS = [
  "postgres",
  "mysql",
  "sqlite",
  "mssql",
  "oracle",
  "clickhouse",
  "mongodb",
  "redis",
  "elasticsearch",
  "cassandra",
  "dynamodb",
  "neo4j",
] as const;
export type EngineId = (typeof ENGINE_IDS)[number];

export const FILTER_OPS = ["eq", "ne", "gt", "gte", "lt", "lte", "contains", "starts", "null", "notnull"] as const;
export type FilterOp = (typeof FILTER_OPS)[number];
const ALL_OPS: FilterOp[] = [...FILTER_OPS];
const COMPARE_OPS: FilterOp[] = ["eq", "ne", "gt", "gte", "lt", "lte"];

export type ConnectionFieldId = "host" | "port" | "user" | "password" | "database" | "file" | "serviceName" | "localDataCenter" | "region" | "endpoint" | "accessKeyId" | "authSource" | "apiKey";

export interface EngineInfo {
  id: EngineId;
  label: string;
  // Other products that speak the same protocol, shown so a user can find them.
  alsoWorksWith: string;
  defaultPort: number | null;
  fields: ConnectionFieldId[];
  // Labels for the levels above an object; null means the engine has no such level.
  databaseLabel: string | null;
  schemaLabel: string | null;
  objectLabel: string;
  queryLanguage: string;
  queryPlaceholder: string;
  // Text put in the query box by "New <object>". The user edits it and runs it as a normal query.
  createTemplate: string;
  // Prepended to the query for the Explain button. Null means the engine has none.
  explainPrefix: string | null;
  filterOps: FilterOp[];
  canSort: boolean;
  // Whether rows can be edited from the grid at all; a given object may still lack a key.
  canEditRows: boolean;
  canInsertRows: boolean;
  canTruncate: boolean;
  canDrop: boolean;
  // Whether import can run inside one transaction, so a failure leaves nothing behind.
  transactionalImport: boolean;
  // Keeps whatever type a value has and accepts new fields, so CSV numbers should not stay text.
  schemaless: boolean;
  exportSqlInserts: boolean;
  supportsTls: boolean;
  supportsSsh: boolean;
  supportsCancel: boolean;
}

